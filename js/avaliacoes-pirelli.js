  // Define o filtro ativo e renderiza
  window.setReviewsFilter = function(filterType) {
    activeFilter = filterType;
    
    // Destaca o chip ativo
    const chips = document.querySelectorAll('.reviews-modal-filter-chip');
    chips.forEach(c => c.classList.remove('active'));
    
    const activeChip = document.getElementById(`filter-chip-${filterType}`);
    if (activeChip) activeChip.classList.add('active');

    // Filtra as avaliações
    let filteredList = [];
    let starsOverride = null;

    if (filterType === 'imagens') {
      filteredList = PIRELLI_REVIEWS.filter(r => r.photos && r.photos.length > 0);
    } else if (filterType === '5') {
      filteredList = PIRELLI_REVIEWS.filter(r => r.stars === 5);
    } else if (filterType === '4' || filterType === '3' || filterType === '2' || filterType === '1') {
      const targetStars = parseInt(filterType);
      filteredList = PIRELLI_REVIEWS.filter(r => r.stars === targetStars);
      
      // Fallback: se não tiver avaliações suficientes da estrela selecionada,
      // pegamos avaliações de 5 estrelas e redefinimos visualmente suas estrelas para o filtro alvo.
      if (filteredList.length < 5) {
        // Usa fatias totalmente diferentes para cada estrela para evitar duplicar avaliações no filtro
        let sliceStart = 0;
        if (targetStars === 4) sliceStart = 10;
        else if (targetStars === 3) sliceStart = 30;
        else if (targetStars === 2) sliceStart = 50;
        else if (targetStars === 1) sliceStart = 70;
        
        const fallbacks = PIRELLI_REVIEWS.filter(r => r.stars === 5).slice(sliceStart, sliceStart + 15);
        filteredList = filteredList.concat(fallbacks);
        starsOverride = targetStars;
      }
    } else if (filterType === 'acompanhamento') {
      // Filtramos avaliações com comentários maiores para simular acompanhamento
      filteredList = PIRELLI_REVIEWS.filter(r => r.comment && r.comment.length > 30).slice(0, 12);
    }

    renderReviewsInModal(filteredList, starsOverride, filterType === 'acompanhamento');
  };

