$dir = "c:\Users\eduar\OneDrive\Documentos\TT\pages"
$files = Get-ChildItem -Path $dir -Filter "*.html"
$encUTF8 = New-Object System.Text.UTF8Encoding($false)
$pattern = '<div class="review-user-name">An.nimo</div>'

$totalSubs = 0

foreach ($file in $files) {
    $bytes = [System.IO.File]::ReadAllBytes($file.FullName)
    $content = [System.Text.Encoding]::UTF8.GetString($bytes)
    
    $matchList = [regex]::Matches($content, $pattern)
    if ($matchList.Count -eq 0) { continue }
    
    Write-Host "$($file.Name): $($matchList.Count) ocorrencias"
    
    # Substitui manualmente um por um para controlar o índice
    $sb = New-Object System.Text.StringBuilder
    $lastPos = 0
    foreach ($m in $matchList) {
        # Adiciona o texto antes desse match
        [void]$sb.Append($content.Substring($lastPos, $m.Index - $lastPos))
        # Adiciona o novo username
        $username = $usernames[$totalSubs % $usernames.Count]
        [void]$sb.Append("<div class=`"review-user-name`">$username</div>")
        $totalSubs++
        $lastPos = $m.Index + $m.Length
    }
    # Adiciona o resto do conteúdo
    [void]$sb.Append($content.Substring($lastPos))
    
    $newBytes = $encUTF8.GetBytes($sb.ToString())
    [System.IO.File]::WriteAllBytes($file.FullName, $newBytes)
}

Write-Host "Concluido! Total de substituicoes: $totalSubs"
